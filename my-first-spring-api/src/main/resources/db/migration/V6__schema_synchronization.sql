-- Synchronization migration to ensure production DB aligns with JPA entities.
-- This fixes the BeanCreationException caused by missing tables in production.

CREATE TABLE IF NOT EXISTS ledger_events (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at timestamp(6) NOT NULL,
    updated_at timestamp(6),
    event_type varchar(255) NOT NULL,
    amount decimal(19,2) NOT NULL,
    currency varchar(10) DEFAULT 'INR',
    description text,
    user_id bigint,
    kitchen_id bigint,
    order_id bigint,
    status varchar(50) NOT NULL,
    metadata jsonb
);

CREATE TABLE IF NOT EXISTS seller_feature_grants (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at timestamp(6) NOT NULL,
    updated_at timestamp(6),
    seller_id bigint NOT NULL,
    feature_key varchar(255) NOT NULL,
    grant_type varchar(50) NOT NULL,
    expires_at timestamp(6),
    granted_by_id bigint,
    CONSTRAINT fk_grants_seller FOREIGN KEY (seller_id) REFERENCES users (id)
);

CREATE INDEX idx_ledger_user ON ledger_events (user_id);
CREATE INDEX idx_ledger_kitchen ON ledger_events (kitchen_id);
CREATE INDEX idx_grants_seller_feature ON seller_feature_grants (seller_id, feature_key);

-- Public URL logic: a dedicated, unique, indexed slug per kitchen, plus an
-- alias table so an Admin slug change never breaks an already-shared link.
--
-- The slug is authoritative for /kitchen/{slug}. The legacy unique `name`
-- column is retained and kept in step with the slug for new/backfilled rows,
-- so every existing findByName(...) caller keeps working unchanged.

ALTER TABLE kitchens ADD COLUMN IF NOT EXISTS slug varchar(255);

-- Backfill: copy the current name (which already held a slug-like value) into
-- the new slug column. name was already unique, so this is effectively a 1:1
-- copy; the de-duplication below only guards against a non-unique edge state.
UPDATE kitchens SET slug = name WHERE slug IS NULL OR slug = '';

-- Guarantee uniqueness before the index is added. Any residual duplicates get
-- a deterministic numeric suffix ordered by id. Deliberately written as a
-- correlated UPDATE (rather than a windowed CTE with UPDATE ... FROM, which
-- PostgreSQL supports) so the statement is ALSO valid on the H2
-- PostgreSQL-compatibility mode the schema-validation tests run Flyway
-- against: every later row for the same slug gets -2, -3, ... in id order
-- while the first row keeps the bare value.
UPDATE kitchens k
SET slug = k.slug || '-' || (
    SELECT COUNT(*) FROM kitchens o
    WHERE o.slug = k.slug AND o.id <= k.id
)
WHERE EXISTS (
    SELECT 1 FROM kitchens o
    WHERE o.slug = k.slug AND o.id < k.id
);

CREATE UNIQUE INDEX IF NOT EXISTS idx_kitchens_slug ON kitchens (slug);
ALTER TABLE kitchens ALTER COLUMN slug SET NOT NULL;

-- Retired slugs kept as permanent redirects to their kitchen.
CREATE TABLE IF NOT EXISTS kitchen_slug_aliases (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    old_slug varchar(255) NOT NULL UNIQUE,
    kitchen_id bigint NOT NULL,
    created_at timestamp(6)
);

ALTER TABLE kitchen_slug_aliases DROP CONSTRAINT IF EXISTS fk_slug_aliases_kitchen;
ALTER TABLE kitchen_slug_aliases
    ADD CONSTRAINT fk_slug_aliases_kitchen FOREIGN KEY (kitchen_id) REFERENCES kitchens (id);
